def para(text, align=None, bold=False):
    p = doc.add_paragraph()
    r = p.add_run(text)
    r.bold = bold
    if align == 'center':
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    return p


def heading(text):
    p = doc.add_paragraph()
    r = p.add_run(text)
    r.bold = True
    r.font.size = Pt(12)
    return p


def info_table(rows, col_widths=(5.5, 9.5)):
    """Двухколоночная таблица: метка слева, значение справа."""
    from docx.shared import Cm
    table = doc.add_table(rows=len(rows), cols=2)
    table.style = 'Table Grid'
    table.autofit = False
    for ri, (label, value) in enumerate(rows):
        c0, c1 = table.rows[ri].cells
        c0.width = Cm(col_widths[0])
        c1.width = Cm(col_widths[1])
        p0 = c0.paragraphs[0]
        r0 = p0.add_run(label)
        r0.font.name = 'Times New Roman'
        r0.font.size = Pt(12)
        p1 = c1.paragraphs[0]
        r1 = p1.add_run(value)
        r1.font.name = 'Times New Roman'
        r1.font.size = Pt(12)
    return table


